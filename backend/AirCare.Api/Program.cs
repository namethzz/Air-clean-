using System.Text;
using AirCare.Api.Data;
using AirCare.Api.Models;
using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.IdentityModel.Tokens;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddControllers();
builder.Services.AddDbContext<AppDbContext>(o => o.UseSqlite(builder.Configuration.GetConnectionString("DefaultConnection")));
builder.Services.AddScoped<IPasswordHasher<AppUser>, PasswordHasher<AppUser>>();
builder.Services.AddCors(o => o.AddPolicy("Frontend", p => p.WithOrigins("http://localhost:5173", "http://127.0.0.1:5173", "http://localhost:4173").AllowAnyHeader().AllowAnyMethod()));
var jwt = builder.Configuration.GetSection("Jwt");
var key = Encoding.UTF8.GetBytes(jwt["Key"] ?? throw new InvalidOperationException("Jwt:Key is missing"));
builder.Services.AddAuthentication(JwtBearerDefaults.AuthenticationScheme).AddJwtBearer(o => o.TokenValidationParameters = new TokenValidationParameters { ValidateIssuer=true, ValidateAudience=true, ValidateLifetime=true, ValidateIssuerSigningKey=true, ValidIssuer=jwt["Issuer"], ValidAudience=jwt["Audience"], IssuerSigningKey=new SymmetricSecurityKey(key), ClockSkew=TimeSpan.FromSeconds(30) });
builder.Services.AddAuthorization();
var app = builder.Build();
app.UseCors("Frontend"); app.UseAuthentication(); app.UseAuthorization();
app.MapGet("/", () => Results.Ok(new { name="AirCare Connect API", version="1.0.0", status="running" }));
app.MapGet("/health", () => Results.Ok(new { status="healthy", timestamp=DateTime.UtcNow }));
app.MapControllers();
await DemoDataSeeder.SeedAsync(app.Services);
app.Run();